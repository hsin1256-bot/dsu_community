-- 1. 학식 메뉴 테이블 (중식/석식 대신 카테고리별 개별 메뉴 관리)
create table if not exists public.cafeteria_menus (
  id text primary key,
  restaurant text not null,
  category text not null,
  name text not null,
  price text not null,
  menu_items text[] default '{}',
  calories text,
  sort_order integer not null default 0,
  created_at timestamptz not null default now()
);

-- 조회 성능 인덱스 (식당 + 카테고리별 필터링 및 정렬 최적화)
create index if not exists idx_cafeteria_menus_restaurant_category
  on public.cafeteria_menus (restaurant, category, sort_order);

-- 2. 학식 메뉴별 리뷰 테이블
create table if not exists public.meal_reviews (
  id text primary key,
  menu_id text not null references public.cafeteria_menus(id) on delete cascade,
  restaurant text not null,
  menu_name text not null,
  nickname text not null default '동서대 학우',
  date text not null,
  student_email_masked text not null,
  rating smallint not null check (rating between 1 and 5),
  comment text not null,
  photo_url text,
  reported boolean not null default false,
  report_reason text,
  created_at timestamptz not null default now()
);

-- 메뉴별/식당별 리뷰 조회 인덱스
create index if not exists idx_meal_reviews_restaurant_menu
  on public.meal_reviews (restaurant, menu_id, created_at desc);

create index if not exists idx_meal_reviews_menu_name
  on public.meal_reviews (restaurant, menu_name);

-- 3. Row Level Security (RLS) 활성화 및 정책 설정
alter table public.cafeteria_menus enable row level security;
alter table public.meal_reviews enable row level security;

-- 메뉴 조회: 모든 사용자(anon, authenticated) 허용
drop policy if exists "cafeteria_menus_select_public" on public.cafeteria_menus;
create policy "cafeteria_menus_select_public"
  on public.cafeteria_menus
  for select
  to anon, authenticated
  using (true);

-- 리뷰 조회: 모든 사용자 허용
drop policy if exists "meal_reviews_select_public" on public.meal_reviews;
create policy "meal_reviews_select_public"
  on public.meal_reviews
  for select
  to anon, authenticated
  using (true);

-- 리뷰 작성: 허용
drop policy if exists "meal_reviews_insert_public" on public.meal_reviews;
create policy "meal_reviews_insert_public"
  on public.meal_reviews
  for insert
  to anon, authenticated
  with check (rating between 1 and 5 and length(trim(comment)) >= 2);

-- 리뷰 신고 업데이트: 허용
drop policy if exists "meal_reviews_update_report" on public.meal_reviews;
create policy "meal_reviews_update_report"
  on public.meal_reviews
  for update
  to anon, authenticated
  using (true)
  with check (reported = true);

